package whtnt

import (
	"context"
	"fmt"
	"io"
	"net/url"
	"regexp"
	"strings"
	"time"

	http "github.com/bogdanfinn/fhttp"
)

const (
	cfChallengeBaseURL = "https://api.whatnot.com"
	cfClearanceCookie  = "cf_clearance"
)

var cfTokenRe = regexp.MustCompile(`/cdn-cgi/challenge-platform/h/b/jsd/oneshot/([a-f0-9]+)`)

// solveCFChallenge attempts the Cloudflare Bot Management JSD challenge on
// api.whatnot.com using the module's existing iOS tls_client. On success the
// cf_clearance cookie is stored in the client's cookie jar and subsequent API
// requests pass through the CF edge without being re-challenged.
//
// The real iOS app solves this in a WKWebView that executes the Cloudflare JSD
// JavaScript. Without a JS engine we go through the same HTTP requests but
// submit an empty/minimal JSD payload. This succeeds when the IP has a clean
// reputation score; heavily flagged IPs still require a full JS-solved payload
// (use a solver service in that case).
func (m *Module) solveCFChallenge(ctx context.Context) error {
	if m.client == nil {
		return fmt.Errorf("cf_challenge: client is nil")
	}

	// Step 1: initial request to prime CF state and detect challenge.
	challengeToken, err := m.cfInitialRequest(ctx)
	if err != nil {
		return fmt.Errorf("cf_challenge: initial request: %w", err)
	}
	if challengeToken == "" {
		// No challenge — cf_clearance was already set or not required.
		return nil
	}

	// Step 2: fetch the JSD init script (CF expects this request before oneshot).
	// Non-fatal; continue to oneshot even if init fails.
	_ = m.cfFetchJSDInit(ctx, challengeToken)

	time.Sleep(300 * time.Millisecond)

	// Step 3: POST the JSD oneshot to obtain cf_clearance.
	return m.cfPostOneshot(ctx, challengeToken)
}

// cfInitialRequest sends GET / to api.whatnot.com with iOS headers.
// Returns the CF challenge token if a JSD challenge was issued, or "" if none.
func (m *Module) cfInitialRequest(ctx context.Context) (string, error) {
	req, err := http.NewRequestWithContext(ctx, "GET", cfChallengeBaseURL+"/", nil)
	if err != nil {
		return "", err
	}
	m.setCFRequestHeaders(req)

	m.client.SetFollowRedirect(false)
	resp, err := m.client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(resp.Body)

	return extractCFToken(resp, string(body)), nil
}

// cfFetchJSDInit fetches /cdn-cgi/challenge-platform/h/b/jsd/init/{token}.
func (m *Module) cfFetchJSDInit(ctx context.Context, token string) error {
	initURL := cfChallengeBaseURL + "/cdn-cgi/challenge-platform/h/b/jsd/init/" + token
	req, err := http.NewRequestWithContext(ctx, "GET", initURL, nil)
	if err != nil {
		return err
	}
	m.setCFRequestHeaders(req)

	resp, err := m.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	io.ReadAll(resp.Body)
	return nil
}

// cfPostOneshot sends POST /cdn-cgi/challenge-platform/h/b/jsd/oneshot/{token}.
// A successful response sets the cf_clearance cookie.
func (m *Module) cfPostOneshot(ctx context.Context, token string) error {
	oneshotURL := cfChallengeBaseURL + "/cdn-cgi/challenge-platform/h/b/jsd/oneshot/" + token

	// The JSD payload is normally generated by CF's JavaScript running in a
	// browser/WebView. Without JS execution we send the minimal form body
	// that CF accepts for clean IPs. On flagged IPs this will 403; integrate
	// a solver service (e.g. capsolver, nopecha) to generate a real payload.
	payload := url.Values{}
	payload.Set("md", "")
	payload.Set("r", token)

	req, err := http.NewRequestWithContext(ctx, "POST", oneshotURL,
		strings.NewReader(payload.Encode()))
	if err != nil {
		return err
	}
	m.setCFRequestHeaders(req)
	req.Header.Set("content-type", "application/x-www-form-urlencoded")
	req.Header.Set("origin", cfChallengeBaseURL)
	req.Header.Set("referer", cfChallengeBaseURL+"/")

	resp, err := m.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	io.ReadAll(resp.Body)

	if resp.StatusCode >= 400 {
		return fmt.Errorf("cf oneshot returned %d — IP likely flagged, use JS solver", resp.StatusCode)
	}

	// Verify cf_clearance was set.
	parsed, _ := url.Parse(cfChallengeBaseURL)
	if parsed != nil && m.client.GetCookieJar() != nil {
		for _, c := range m.client.GetCookieJar().Cookies(parsed) {
			if c.Name == cfClearanceCookie {
				return nil
			}
		}
	}
	return fmt.Errorf("cf oneshot succeeded but %s cookie not found", cfClearanceCookie)
}

func (m *Module) setCFRequestHeaders(req *http.Request) {
	ua := m.mobileUserAgent()
	req.Header = http.Header{
		"user-agent":      {ua},
		"accept":          {"*/*"},
		"accept-language": {"en-US,en;q=0.9"},
		"accept-encoding": {"gzip, deflate, br"},
		http.HeaderOrderKey: {
			"user-agent", "accept", "accept-language",
			"accept-encoding", "content-type", "origin", "referer",
			"cookie",
		},
	}
}

// extractCFToken looks for a CF JSD challenge token in the response.
func extractCFToken(resp *http.Response, body string) string {
	// Check Location header on 302/403 redirect to /cdn-cgi/...
	if loc := resp.Header.Get("Location"); loc != "" {
		if m := cfTokenRe.FindStringSubmatch(loc); len(m) == 2 {
			return m[1]
		}
	}
	// Check body for oneshot URL (CF inlines it in the challenge page).
	if m := cfTokenRe.FindStringSubmatch(body); len(m) == 2 {
		return m[1]
	}
	// Check cf-chl-bypass header (CF Bot Management specific).
	if bypass := resp.Header.Get("cf-chl-bypass"); bypass != "" {
		return bypass
	}
	return ""
}

// hasCFClearance reports whether cf_clearance is already set in the client's
// cookie jar for api.whatnot.com.
func (m *Module) hasCFClearance() bool {
	if m.client == nil || m.client.GetCookieJar() == nil {
		return false
	}
	parsed, err := url.Parse(cfChallengeBaseURL)
	if err != nil {
		return false
	}
	for _, c := range m.client.GetCookieJar().Cookies(parsed) {
		if c.Name == cfClearanceCookie {
			return true
		}
	}
	return false
}

// needsCFChallengeFromClient returns true when we should attempt to solve the
// CF challenge. Checks whether cf_clearance is missing from the client jar.
func (m *Module) needsCFChallengeFromClient() bool {
	return !m.hasCFClearance()
}

// mobileUserAgent returns the iOS app user-agent for CF challenge requests.
func (m *Module) mobileUserAgent() string {
	return m.whatnotIOSUserAgent(m.seonIOSVersion(), m.deviceMachine())
}

// cfSolveOrSkip calls solveCFChallenge and logs the result; errors are
// non-fatal so the caller can proceed and see if the API accepts the session.
func (m *Module) cfSolveOrSkip(ctx context.Context) {
	if !m.needsCFChallengeFromClient() {
		return
	}
	if err := m.solveCFChallenge(ctx); err != nil {
		if m.log != nil {
			m.log.Manager(fmt.Sprintf("CF challenge skipped: %v", err))
		}
	}
}
